def analyze_college_syllabus_gap(file_name: str, syllabus_text: str, domain_category: str = 'Machine Learning & AI') -> dict:
    if not syllabus_text:
        return {
            "status": "Error",
            "message": "Syllabus file content could not be extracted or is empty."
        }

    target_industry_skills = INDUSTRY_SKILL_BENCHMARKS.get(
        domain_category,
        INDUSTRY_SKILL_BENCHMARKS['Machine Learning & AI']
    )

    syllabus_text_lower = syllabus_text.lower()
    covered_skills = []
    missing_skills = []

    # Check presence of each skill in syllabus text
    for skill in target_industry_skills:
        # Regex search for exact term or boundary matches
        pattern = r'\b' + re.escape(skill.lower()) + r'\b'
        if re.search(pattern, syllabus_text_lower) or skill.lower() in syllabus_text_lower:
            covered_skills.append(skill)
        else:
            missing_skills.append(skill)

    # ACCURATE SCORE MATHEMATICS: Pure Skill Ratio Formula
    total_required = len(target_industry_skills)
    total_covered = len(covered_skills)

    if total_required > 0:
        coverage_score = (total_covered / total_required) * 100.0
    else:
        coverage_score = 0.0

    alignment_percentage = round(coverage_score, 2)

    # Actionable Recommendations
    recommendations = []
    if missing_skills:
        recommendations.append(f"💡 Curriculum Action Item: Add modules covering [{', '.join(missing_skills)}] to align with 100% industry demand.")
        recommendations.append(f"📌 Suggested Lab Practical: Introduce hands-on projects involving [{missing_skills[0]}].")
    else:
        recommendations.append("🎉 Outstanding! Your curriculum fully covers modern industry requirements.")

    return {
        "uploaded_syllabus_file": file_name,
        "domain_category": domain_category,
        "syllabus_alignment_score": f"{alignment_percentage}%",
        "covered_industry_skills_count": f"{total_covered} / {total_required} Skills Covered",
        "covered_industry_skills": covered_skills,
        "missing_outdated_skills": missing_skills,
        "curriculum_update_recommendations": recommendations
    }


