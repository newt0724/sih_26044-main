def generate_tpo_batch_analytics(batch_evaluations_list: list) -> dict:
    if not batch_evaluations_list:
        return {"status": "Error", "message": "No student evaluation data provided."}

    total_students = len(batch_evaluations_list)
    scores = []
    fraud_count = 0
    shortlisted_count = 0
    missing_skills_counter = {}

    for student in batch_evaluations_list:
        score = student.get('final_ai_match_score', 0.0)
        scores.append(score)

        if student.get('fraud_detected', False):
            fraud_count += 1

        if 'Shortlisted' in student.get('final_decision_status', ''):
            shortlisted_count += 1

        recommendations = student.get('role_specific_recommendations', [])
        for rec in recommendations:
            if "'" in rec:
                skill = rec.split("'")[1]
                missing_skills_counter[skill] = missing_skills_counter.get(skill, 0) + 1

    avg_batch_score = round(float(np.mean(scores)), 2) if scores else 0.0
    job_readiness_rate = round((shortlisted_count / total_students) * 100, 2)
    fraud_rate = round((fraud_count / total_students) * 100, 2)

    sorted_missing_skills = sorted(missing_skills_counter.items(), key=lambda x: x[1], reverse=True)
    batch_skill_deficits = [
        f"{skill}: Missing in {count} students ({round((count/total_students)*100, 1)}% of batch)"
        for skill, count in sorted_missing_skills
    ]

    return {
        "total_students_evaluated": total_students,
        "average_batch_employability_score": f"{avg_batch_score}%",
        "job_ready_students_count": f"{shortlisted_count} / {total_students} ({job_readiness_rate}%)",
        "fraud_flagged_resumes_count": f"{fraud_count} Students ({fraud_rate}%)",
        "top_batch_skill_deficits_heatmap": batch_skill_deficits
    }


