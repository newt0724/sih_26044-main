# 1. AUTOMATED FRAUD & RISK AUDIT SCANNER (TPO PRE-SCREENING)
# ---------------------------------------------------------------------
def run_tpo_pre_screening_audit(batch_evaluations_list: list) -> dict:
    """
    Categorizes all batch resumes into High-Risk (Fraud), Medium-Risk (Missing Proofs),
    and Clean Verified profiles for TPO pre-placement audits.
    """
    if not batch_evaluations_list:
        return {"status": "Error", "message": "No student evaluation data provided."}

    high_risk_flagged = []
    medium_risk_warnings = []
    clean_verified = []

    for student in batch_evaluations_list:
        name = student.get('candidate_name', 'Unknown Candidate')
        score = student.get('final_ai_match_score', 0.0)
        is_fraud = student.get('fraud_detected', False)
        status = student.get('final_decision_status', '')

        student_summary = {
            "name": name,
            "score": f"{score}%",
            "decision": status
        }

        if is_fraud or "Flagged" in status:
            high_risk_flagged.append(student_summary)
        elif "Warning" in status:
            medium_risk_warnings.append(student_summary)
        else:
            clean_verified.append(student_summary)

    return {
        "total_audited": len(batch_evaluations_list),
        "high_risk_fraud_count": len(high_risk_flagged),
        "medium_risk_warning_count": len(medium_risk_warnings),
        "verified_clean_count": len(clean_verified),
        "audit_breakdown": {
            "🔴 High Risk (Flagged Fraud)": high_risk_flagged,
            "🟡 Medium Risk (Missing Proofs)": medium_risk_warnings,
            "🟢 Clean Verified Profiles": clean_verified
        }
    }


# ---------------------------------------------------------------------
# 2. VERIFIED TALENT EXPORTER FOR CORPORATE DRIVE
# ---------------------------------------------------------------------
def export_verified_candidate_list(batch_evaluations_list: list, score_cutoff: float = 60.0) -> list:
    """
    Filters out fraud profiles and outputs top pre-screened job-ready candidates
    matching the recruiter's minimum score cutoff.
    """
    if not batch_evaluations_list:
        return []

    verified_shortlist = []

    for student in batch_evaluations_list:
        score = student.get('final_ai_match_score', 0.0)
        is_fraud = student.get('fraud_detected', False)

        # Eligibility Check: No fraud + Score >= Cutoff
        if not is_fraud and score >= score_cutoff:
            verified_shortlist.append({
                "Candidate Name": student.get('candidate_name'),
                "Final AI Score": f"{score}%",
                "Decision Status": student.get('final_decision_status'),
                "Proof-of-Work Verified": "Yes"
            })

    # Sort candidates by highest score first
    verified_shortlist = sorted(verified_shortlist, key=lambda x: float(x["Final AI Score"].replace('%', '')), reverse=True)
    return verified_shortlist


