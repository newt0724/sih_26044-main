def upload_and_extract_syllabus_text() -> tuple:
    print("👇 Kripya College Syllabus ka Document (PDF/JPG/PNG) upload karein:\n")
    uploaded = files.upload()

    if not uploaded:
        print("❌ Koi file upload nahi hui!")
        return None, ""

    file_name = list(uploaded.keys())[0]
    print(f"\n✅ Syllabus Document Received: '{file_name}' | Reading Content...\n")

    extracted_text = ""
    is_scanned_pdf = False

    if file_name.lower().endswith('.pdf'):
        try:
            with pdfplumber.open(file_name) as pdf:
                for page in pdf.pages:
                    text = page.extract_text()
                    if text:
                        extracted_text += text + "\n"
                    else:
                        is_scanned_pdf = True
        except Exception:
            is_scanned_pdf = True

    # OCR Fallback for scanned PDF or Image files
    if is_scanned_pdf or file_name.lower().endswith(('.png', '.jpg', '.jpeg')):
        print("🔍 Scanned / Image File detected! Running Tesseract OCR Engine...")
        try:
            if file_name.lower().endswith(('.png', '.jpg', '.jpeg')):
                img = cv2.imread(file_name)
                extracted_text = pytesseract.image_to_string(img)
            else:
                images = convert_from_path(file_name)
                for img in images:
                    extracted_text += pytesseract.image_to_string(img) + "\n"
        except Exception as e:
            print(f"⚠️ Syllabus OCR Error: {e}")

    return file_name, extracted_text.strip()


