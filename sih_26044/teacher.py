def plot_visual_batch_heatmap(batch_evaluations_list: list, save_filename: str = 'tpo_batch_skill_heatmap.png'):
    if not batch_evaluations_list:
        print("❌ No evaluation data to plot heatmap!")
        return

    total_students = len(batch_evaluations_list)
    missing_skills_counter = {}

    for student in batch_evaluations_list:
        recommendations = student.get('role_specific_recommendations', [])
        for rec in recommendations:
            if "'" in rec:
                skill = rec.split("'")[1]
                missing_skills_counter[skill] = missing_skills_counter.get(skill, 0) + 1

    if not missing_skills_counter:
        print("🎉 No skill deficits found in the batch!")
        return

    sorted_skills = sorted(missing_skills_counter.items(), key=lambda x: x[1], reverse=True)
    skills = [item[0] for item in sorted_skills]
    counts = [item[1] for item in sorted_skills]
    percentages = [(c / total_students) * 100 for c in counts]

    heatmap_matrix = np.array(percentages).reshape(-1, 1)

    plt.figure(figsize=(10, max(4, len(skills) * 0.9)))
    annot_matrix = np.array([f"{count}/{total_students} Students\n({pct:.1f}%)" for count, pct in zip(counts, percentages)]).reshape(-1, 1)

    sns.heatmap(
        heatmap_matrix,
        annot=annot_matrix,
        fmt="",
        cmap="YlOrRd",
        yticklabels=skills,
        xticklabels=["Batch Skill Deficit Level (%)"],
        linewidths=1.5,
        linecolor='white',
        cbar_kws={'label': 'Skill Deficit Percentage (%)'},
        annot_kws={"size": 11, "weight": "bold"}
    )

    plt.title(f"Institutional Batch Skill Deficit Heatmap (Total Students: {total_students})", fontsize=14, fontweight='bold', pad=15)
    plt.ylabel("Core Industry Skills", fontsize=12, fontweight='bold')
    plt.tight_layout()

    plt.savefig(save_filename, dpi=300)
    plt.show()
    print(f"✅ Visual Heatmap chart successfully saved as '{save_filename}'!")


