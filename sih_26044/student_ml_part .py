def process_uploaded_resume_file():
    print("👇 Niche 'Choose Files' button par click karke Candidate Resume (PDF/JPG/PNG) upload karein:\n")
    uploaded = files.upload()

    if not uploaded:
        print("❌ Koi file upload nahi hui!")
        return None

    file_name = list(uploaded.keys())[0]
    print(f"\n✅ File Received: '{file_name}' | Processing Started...\n")

    hidden_keywords = []
    is_scanned_pdf = False

    if file_name.lower().endswith('.pdf'):
        try:
            with pdfplumber.open(file_name) as pdf:
                for page in pdf.pages:
                    words = page.extract_words(extra_attrs=["non_stroking_color", "size"])

                    if not words:
                        is_scanned_pdf = True

                    for word in words:
                        text = word['text']
                        font_size = word['size']
                        color = word.get('non_stroking_color')

                        is_white = color in [(1, 1, 1), (255, 255, 255), [1, 1, 1], [255, 255, 255]]
                        is_tiny = font_size < 3.0

                        if is_white or is_tiny:
                            hidden_keywords.append(text)
        except Exception as e:
            print(f"⚠️ PDF Inspection Note: {e}")
            is_scanned_pdf = True

    is_fraudulent = len(hidden_keywords) > 0
    penalty = -20.0 if is_fraudulent else 0.0

    extracted_text = ""
    if is_scanned_pdf or file_name.lower().endswith(('.png', '.jpg', '.jpeg')):
        print("🔍 Scanned / Image File detected! Running Tesseract OCR Engine...")
        try:
            if file_name.lower().endswith(('.png', '.jpg', '.jpeg')):
                img = cv2.imread(file_name)
                extracted_text = pytesseract.image_to_string(img)
            else:
                images = convert_from_path(file_name)
                for img in images:
                    extracted_text += pytesseract.image_to_string(img) + "\n"
        except Exception as e:
            print(f"❌ OCR Extraction Error: {e}")
    else:
        with pdfplumber.open(file_name) as pdf:
            for page in pdf.pages:
                extracted_text += (page.extract_text() or "") + "\n"

    return {
        "file_name": file_name,
        "extracted_text_preview": extracted_text.strip(),
        "fraud_detected": is_fraudulent,
        "hidden_keywords_caught": hidden_keywords,
        "score_penalty": penalty
    }

