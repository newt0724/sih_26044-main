# 1. TEXT MATCHING & SEMANTIC SIMILARITY
def calculate_semantic_similarity(resume_text: str, job_description_text: str) -> dict:
    if not resume_text or not job_description_text:
        return {"semantic_match_score": 50.0, "match_quality": "Standard Match"}

    try:
        vectorizer = TfidfVectorizer(stop_words='english', ngram_range=(1, 2))
        tfidf_matrix = vectorizer.fit_transform([resume_text, job_description_text])
        sim_score = cosine_similarity(tfidf_matrix[0:1], tfidf_matrix[1:2])[0][0]
        similarity_percentage = round(float(sim_score) * 100, 2)
        quality = "High Match" if similarity_percentage >= 60.0 else "Moderate Match"
        return {"semantic_match_score": similarity_percentage, "match_quality": quality}
    except Exception as e:
        return {"semantic_match_score": 50.0, "match_quality": "Standard Match"}

# 2. RESUME LINK EXTRACTION
def extract_entities_from_resume_text(resume_text: str) -> dict:
    github_pattern = r'https?://(?:www\.)?github\.com/[a-zA-Z0-9_-]+'
    linkedin_pattern = r'https?://(?:www\.)?linkedin\.com/in/[a-zA-Z0-9_-]+'

    gh = re.findall(github_pattern, resume_text, re.IGNORECASE)
    li = re.findall(linkedin_pattern, resume_text, re.IGNORECASE)

    return {"github_url": gh[0] if gh else None, "linkedin_url": li[0] if li else None}

# 3. GITHUB PROOF-OF-WORK SCRAPER
def analyze_github_proof_of_work(github_url_or_username: str) -> dict:
    if not github_url_or_username:
        return {"valid_profile": False, "proof_of_work_score": 0.0, "tech_stack": []}

    username = github_url_or_username.strip().rstrip('/')
    if 'github.com/' in username:
        username = username.split('github.com/')[-1]
    username = username.split('/')[0]

    headers = {"User-Agent": "Mozilla/5.0"}
    try:
        user_res = requests.get(f"https://api.github.com/users/{username}", headers=headers, timeout=4)
        if user_res.status_code != 200:
            return {"valid_profile": False, "proof_of_work_score": 0.0, "tech_stack": []}

        public_repos = user_res.json().get('public_repos', 0)
        repos_res = requests.get(f"https://api.github.com/users/{username}/repos?per_page=100", headers=headers, timeout=4)
        stars = 0
        languages = set()

        if repos_res.status_code == 200:
            for repo in repos_res.json():
                if not repo.get('fork', False):
                    stars += repo.get('stargazers_count', 0)
                    if repo.get('language'):
                        languages.add(repo.get('language'))

        total_score = min(100.0, round(min(30, public_repos * 3) + min(30, stars * 5) + min(20, len(languages) * 5) + (20 if public_repos > 0 else 0), 2))
        return {"valid_profile": True, "username": username, "tech_stack": list(languages), "proof_of_work_score": total_score}
    except Exception:
        return {"valid_profile": False, "proof_of_work_score": 0.0, "tech_stack": []}

# 4. LINKEDIN PRESENCE CHECK
def analyze_linkedin_profile(linkedin_url: str) -> dict:
    if not linkedin_url:
        return {"has_linkedin": False, "status": "No LinkedIn Profile Linked"}
    is_valid = bool(re.match(r'https?://(?:www\.)?linkedin\.com/in/[a-zA-Z0-9_-]+', linkedin_url, re.IGNORECASE))
    return {"has_linkedin": is_valid, "status": "Verified Active LinkedIn" if is_valid else "Invalid URL"}

