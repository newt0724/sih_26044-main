def run_interactive_coding_assessment(candidate_skills: list) -> dict:
    print("\n" + "="*60)
    print("💻 INTERACTIVE CODING ASSESSMENT (10 Questions | Skill Matched)")
    print("="*60)

    skills_lower = [s.lower().strip() for s in candidate_skills]
    relevant = [q for q in CODING_QUESTIONS_BANK if any(kw in skill for skill in skills_lower for kw in q['keywords'])]

    if len(relevant) < 10:
        remaining = [q for q in CODING_QUESTIONS_BANK if q not in relevant]
        random.shuffle(remaining)
        relevant.extend(remaining)

    selected = relevant[:10]
    score = 0
    for idx, q in enumerate(selected, 1):
        print(f"Q{idx}. [{q['topic']}] Code:")
        print(q['code'])
        user_ans = input("👉 Fill missing blank: ").strip()
        if user_ans.lower() == q['answer'].lower():
            print("✅ Correct! (+1 Mark)\n")
            score += 1
        else:
            print(f"❌ Incorrect. (Answer: '{q['answer']}')\n")

    return {"coding_score": score, "coding_bonus_percentage": score * 1.0}

def generate_role_specific_recommendations(candidate_skills: list, target_role: str) -> list:
    benchmarks = {
        'machine learning intern': ['Python', 'Scikit-Learn', 'Pandas', 'NumPy', 'SQL', 'Git'],
        'machine learning engineer': ['Python', 'PyTorch', 'TensorFlow', 'FastAPI', 'Docker', 'MLOps', 'SQL'],
        'ai researcher': ['Python', 'PyTorch', 'TensorFlow', 'Deep Learning', 'NLP', 'Computer Vision'],
        'data scientist': ['Python', 'SQL', 'Pandas', 'Statistics', 'Scikit-Learn', 'Tableau']
    }
    required = benchmarks.get(target_role.lower().strip(), ['Python', 'SQL', 'Git', 'Docker'])
    cand_lower = [s.lower().strip() for s in candidate_skills]
    missing = [s for s in required if s.lower() not in cand_lower]
    return [f"Learn '{m}' to fulfill core requirements for '{target_role}'." for m in missing]

