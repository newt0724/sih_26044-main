def evaluate_candidate(candidate_payload: dict) -> dict:
    """
    Main function to be called by Backend Developer (FastAPI / Express Controller)
    """
    form = candidate_payload.get("candidate_form", {})
    file_path = candidate_payload.get("resume_file_path")
    has_cert_proof = candidate_payload.get("has_certification_proof", True)
    coding_score = candidate_payload.get("coding_assessment_score", 0) # 0 to 10

    # 1. Resume Inspection
    resume_analysis = inspect_and_extract_resume(file_path)

    # 2. ML Baseline Model Prediction
    df_input = pd.DataFrame([form])
    raw_ml_score = float(reg_model.predict(df_input)[0])
    ml_decision = int(clf_model.predict(df_input)[0])

    # 3. Social Auto Link Extraction
    links = extract_social_links(resume_analysis["extracted_text"])
    gh_url = form.get("GitHub_URL") or links["github_url"]
    li_url = form.get("LinkedIn_URL") or links["linkedin_url"]

    gh_data = analyze_github(gh_url)
    has_linkedin = bool(li_url and "linkedin.com/in/" in li_url.lower())

    # 4. Score Math
    white_text_penalty = resume_analysis["penalty"] # -20.0 if fraud
    cert_penalty = 0.0 if (has_cert_proof or form.get("Certifications", "None").lower() == "none") else -5.0

    github_bonus = (gh_data["score"] / 100.0) * 10.0
    linkedin_bonus = 5.0 if has_linkedin else 0.0
    coding_bonus = float(coding_score) * 1.0 # 1 Mark = +1%

    total_penalty = white_text_penalty + cert_penalty
    total_bonus = github_bonus + linkedin_bonus + coding_bonus

    final_score = max(0.0, min(100.0, raw_ml_score + total_penalty + total_bonus))

    # Decision
    if resume_analysis["fraud_detected"]:
        status = "Rejected / Flagged (Hidden White-Text Fraud Detected)"
    elif cert_penalty < 0:
        status = "Shortlisted with Warning (Missing Certification Proof)"
    elif ml_decision == 1:
        status = "Shortlisted"
    else:
        status = "Rejected (Low Skill Match)"

    skills_list = [s.strip() for s in form.get("Skills", "").split(",")]
    recs = get_role_recommendations(skills_list, form.get("Job Role", ""))

    return {
        "candidate_name": form.get("Name", "Applicant"),
        "target_role": form.get("Job Role", "N/A"),
        "raw_ml_match_score": round(raw_ml_score, 2),
        "penalties": {
            "white_text_fraud_penalty": white_text_penalty,
            "missing_cert_proof_penalty": cert_penalty,
            "total_penalties": total_penalty
        },
        "bonuses": {
            "github_proof_of_work_bonus": round(github_bonus, 2),
            "linkedin_presence_bonus": linkedin_bonus,
            "coding_assessment_bonus": coding_bonus,
            "total_bonuses": round(total_bonus, 2)
        },
        "final_ai_match_score": round(final_score, 2),
        "final_decision_status": status,
        "fraud_detected": resume_analysis["fraud_detected"],
        "github_analytics": gh_data,
        "role_specific_recommendations": recs
    }

