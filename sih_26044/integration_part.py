def extract_social_links(text: str) -> dict:
    github_pattern = r'https?://(?:www\.)?github\.com/[a-zA-Z0-9_-]+'
    linkedin_pattern = r'https?://(?:www\.)?linkedin\.com/in/[a-zA-Z0-9_-]+'

    gh = re.findall(github_pattern, text, re.IGNORECASE)
    li = re.findall(linkedin_pattern, text, re.IGNORECASE)

    return {
        "github_url": gh[0] if gh else None,
        "linkedin_url": li[0] if li else None
    }

def analyze_github(github_url: str) -> dict:
    if not github_url:
        return {"valid": False, "score": 0.0, "public_repos": 0, "tech_stack": []}

    username = github_url.strip().rstrip('/').split('github.com/')[-1].split('/')[0]
    headers = {"User-Agent": "Mozilla/5.0"}

    try:
        u_res = requests.get(f"https://api.github.com/users/{username}", headers=headers, timeout=4)
        if u_res.status_code != 200:
            return {"valid": False, "score": 0.0, "public_repos": 0, "tech_stack": []}

        u_data = u_res.json()
        public_repos = u_data.get('public_repos', 0)

        r_res = requests.get(f"https://api.github.com/users/{username}/repos?per_page=100", headers=headers, timeout=4)
        stars = 0
        langs = set()
        if r_res.status_code == 200:
            for repo in r_res.json():
                if not repo.get('fork', False):
                    stars += repo.get('stargazers_count', 0)
                    if repo.get('language'):
                        langs.add(repo.get('language'))

        score = min(100.0, (min(30, public_repos * 3) + min(30, stars * 5) + min(20, len(langs) * 5) + (20 if public_repos > 0 else 0)))
        return {"valid": True, "score": score, "public_repos": public_repos, "tech_stack": list(langs)}
    except Exception:
        return {"valid": False, "score": 0.0, "public_repos": 0, "tech_stack": []}


