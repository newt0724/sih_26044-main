# 2. RESUME PARSING & WHITE-TEXT FRAUD INSPECTION
# ---------------------------------------------------------------------
def inspect_and_extract_resume(file_path: str) -> dict:
    if not file_path or not os.path.exists(file_path):
        return {"extracted_text": "", "fraud_detected": False, "hidden_keywords": [], "penalty": 0.0}

    hidden_keywords = []
    is_scanned_pdf = False
    extracted_text = ""

    # Digital PDF Processing
    if file_path.lower().endswith('.pdf'):
        try:
            with pdfplumber.open(file_path) as pdf:
                for page in pdf.pages:
                    words = page.extract_words(extra_attrs=["non_stroking_color", "size"])
                    if not words:
                        is_scanned_pdf = True

                    for word in words:
                        text = word['text']
                        font_size = word['size']
                        color = word.get('non_stroking_color')

                        is_white = color in [(1, 1, 1), (255, 255, 255), [1, 1, 1], [255, 255, 255]]
                        is_tiny = font_size < 3.0

                        if is_white or is_tiny:
                            hidden_keywords.append(text)

                    extracted_text += (page.extract_text() or "") + "\n"
        except Exception:
            is_scanned_pdf = True

    # OCR Fallback for Scanned PDF or Image
    if is_scanned_pdf or file_path.lower().endswith(('.png', '.jpg', '.jpeg')):
        try:
            if file_path.lower().endswith(('.png', '.jpg', '.jpeg')):
                img = cv2.imread(file_path)
                extracted_text = pytesseract.image_to_string(img)
            else:
                images = convert_from_path(file_path)
                for img in images:
                    extracted_text += pytesseract.image_to_string(img) + "\n"
        except Exception as e:
            print(f"OCR Error: {e}")

    is_fraudulent = len(hidden_keywords) > 0
    penalty = -20.0 if is_fraudulent else 0.0

    return {
        "extracted_text": extracted_text.strip(),
        "fraud_detected": is_fraudulent,
        "hidden_keywords": hidden_keywords,
        "penalty": penalty
    }


