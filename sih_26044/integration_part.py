def get_role_recommendations(candidate_skills: list, role: str) -> list:
    benchmarks = {
        'machine learning intern': ['Python', 'Scikit-Learn', 'Pandas', 'NumPy', 'SQL', 'Git'],
        'machine learning engineer': ['Python', 'PyTorch', 'TensorFlow', 'FastAPI', 'Docker', 'MLOps', 'SQL'],
        'ai researcher': ['Python', 'PyTorch', 'TensorFlow', 'Deep Learning', 'NLP', 'Computer Vision'],
        'data scientist': ['Python', 'SQL', 'Pandas', 'Statistics', 'Scikit-Learn', 'Tableau']
    }
    required = benchmarks.get(role.lower().strip(), ['Python', 'SQL', 'Git', 'Docker'])
    cand_lower = [s.lower().strip() for s in candidate_skills]
    missing = [s for s in required if s.lower() not in cand_lower]

    return [f"Learn '{m}' to fulfill core requirements for '{role}'." for m in missing]


